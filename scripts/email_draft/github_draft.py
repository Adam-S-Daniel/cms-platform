"""Open a Decap-shaped editorial draft through the GitHub REST API (urllib only).

The draft looks exactly like one Decap's editorial workflow opens: a `cms/posts/<entry>` branch
off the default branch with one commit, a pull request whose body starts with Decap's marker,
and the `decap-cms/draft` status label. Nothing here merges, approves or adds a publish label.
Every HTTP call goes through an injectable `transport(method, url, headers, body)` returning
`(status, bytes)`, so the tests never touch the network.
"""

from __future__ import annotations

import base64
import json
import urllib.error
import urllib.parse
import urllib.request

API = "https://api.github.com"
DECAP_BODY_MARKER = "Automatically generated by Decap CMS"
DRAFT_LABEL = "decap-cms/draft"
BRANCH_PREFIX = "cms/posts/"
MAX_SUFFIX = 50


class GitHubError(Exception):
    """A GitHub API call failed; carries only the method, a path shape and the status code."""

    def __init__(self, what: str, status: int):
        super().__init__(f"{what} returned HTTP {status}")
        self.what = what
        self.status = status


def urllib_transport(method, url, headers, body):
    req = urllib.request.Request(url, data=body, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            return resp.status, resp.read()
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read() if exc.fp else b""


def marker_for(message_hash: str) -> str:
    return f"<!-- email-draft:{message_hash} -->"


def pr_body(message_hash: str) -> str:
    return f"{DECAP_BODY_MARKER}\n\n{marker_for(message_hash)}\n"


def commit_title(entry_name: str) -> str:
    return f"Create Post “{entry_name}”"


class GitHub:
    def __init__(self, token: str, repo: str, transport=None, api: str = API):
        self.token = token
        self.repo = repo
        self.transport = transport or urllib_transport
        self.api = api.rstrip("/")

    def _call(self, method, path, body=None, ok=(200, 201), what=None):
        headers = {
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "cms-platform-email-draft",
        }
        data = None
        if body is not None:
            data = json.dumps(body).encode("utf-8")
            headers["Content-Type"] = "application/json"
        status, raw = self.transport(method, f"{self.api}/repos/{self.repo}{path}", headers, data)
        if status not in ok:
            raise GitHubError(what or method, status)
        try:
            return status, (json.loads(raw) if raw else None)
        except ValueError as exc:
            raise GitHubError(what or method, status) from exc

    @staticmethod
    def _q(ref: str) -> str:
        return urllib.parse.quote(ref, safe="/")

    # ---- reads ---------------------------------------------------------

    def find_existing_draft(self, message_hash: str) -> str | None:
        """Entry name of a pull request (newest 100, any state) carrying this email's marker."""
        _, pulls = self._call(
            "GET", "/pulls?state=all&sort=created&direction=desc&per_page=100", what="list pulls"
        )
        marker = marker_for(message_hash)
        for pr in pulls or []:
            if marker in (pr.get("body") or ""):
                ref = (pr.get("head") or {}).get("ref", "")
                return ref[len(BRANCH_PREFIX) :] if ref.startswith(BRANCH_PREFIX) else ref
        return None

    def default_branch_head(self) -> tuple[str, str, str]:
        """(default branch, head commit sha, head tree sha)."""
        _, repo = self._call("GET", "", what="get repo")
        branch = repo["default_branch"]
        _, ref = self._call("GET", f"/git/ref/heads/{self._q(branch)}", what="get default ref")
        sha = ref["object"]["sha"]
        _, commit = self._call("GET", f"/git/commits/{sha}", what="get head commit")
        return branch, sha, commit["tree"]["sha"]

    def branch_exists(self, branch: str) -> bool:
        status, _ = self._call(
            "GET", f"/git/ref/heads/{self._q(branch)}", ok=(200, 404), what="get branch"
        )
        return status == 200

    def file_exists(self, path: str, ref: str) -> bool:
        status, _ = self._call(
            "GET",
            f"/contents/{self._q(path)}?ref={urllib.parse.quote(ref, safe='')}",
            ok=(200, 404),
            what="get file",
        )
        return status == 200

    # ---- writes --------------------------------------------------------

    def create_draft(
        self,
        *,
        entry_name: str,
        files: dict[str, bytes],
        message_hash: str,
        base: str,
        head_sha: str,
        tree_sha: str,
    ) -> int:
        """Branch, one commit with every file, pull request and draft label; returns the PR."""
        tree = []
        for path, content in files.items():
            _, blob = self._call(
                "POST",
                "/git/blobs",
                {"content": base64.b64encode(content).decode("ascii"), "encoding": "base64"},
                what="create blob",
            )
            tree.append({"path": path, "mode": "100644", "type": "blob", "sha": blob["sha"]})
        _, new_tree = self._call(
            "POST", "/git/trees", {"base_tree": tree_sha, "tree": tree}, what="create tree"
        )
        title = commit_title(entry_name)
        _, commit = self._call(
            "POST",
            "/git/commits",
            {"message": title, "tree": new_tree["sha"], "parents": [head_sha]},
            what="create commit",
        )
        branch = BRANCH_PREFIX + entry_name
        self._call(
            "POST",
            "/git/refs",
            {"ref": f"refs/heads/{branch}", "sha": commit["sha"]},
            what="create branch",
        )
        _, pr = self._call(
            "POST",
            "/pulls",
            {"title": title, "head": branch, "base": base, "body": pr_body(message_hash)},
            what="create pull",
        )
        self._call(
            "POST", f"/issues/{pr['number']}/labels", {"labels": [DRAFT_LABEL]}, what="add label"
        )
        return pr["number"]

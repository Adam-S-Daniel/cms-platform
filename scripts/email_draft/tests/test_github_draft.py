"""Tests for github_draft.py against an in-memory GitHub REST API."""

import base64

import github_draft
import pytest
from fakes import SECRET_BODY, FakeGitHubApi

REPO = "example-owner/example-site"


def client(api):
    return github_draft.GitHub("gh-token", REPO, transport=api)


def test_create_draft_is_decap_shaped():
    api = FakeGitHubApi()
    gh = client(api)
    base, head, tree = gh.default_branch_head()
    assert (base, head, tree) == ("main", "headsha", "treesha")
    files = {
        "_posts/2026-11-06-x.md": b"---\ntitle: x\n---\n",
        "assets/images/uploads/x-1.png": b"P",
    }
    number = gh.create_draft(
        entry_name="2026-11-06-x",
        files=files,
        message_hash="abc",
        base=base,
        head_sha=head,
        tree_sha=tree,
    )
    assert number == 42
    writes = [(m, p, b) for m, p, b in api.calls if m != "GET"]
    assert [p for _, p, _ in writes] == [
        "/git/blobs",
        "/git/blobs",
        "/git/trees",
        "/git/commits",
        "/git/refs",
        "/pulls",
        "/issues/42/labels",
    ]
    assert base64.b64decode(writes[0][2]["content"]) == files["_posts/2026-11-06-x.md"]
    tree_body = writes[2][2]
    assert tree_body["base_tree"] == "treesha"
    assert [t["path"] for t in tree_body["tree"]] == list(files)
    assert writes[3][2]["message"] == "Create Post “2026-11-06-x”"
    assert writes[3][2]["parents"] == ["headsha"]
    assert writes[4][2]["ref"] == "refs/heads/cms/posts/2026-11-06-x"
    pr = writes[5][2]
    assert pr["head"] == "cms/posts/2026-11-06-x" and pr["base"] == "main"
    assert pr["title"] == "Create Post “2026-11-06-x”"
    assert pr["body"].startswith("Automatically generated by Decap CMS\n\n<!-- email-draft:abc -->")
    assert writes[6][2] == {"labels": ["decap-cms/draft"]}
    # Never merges, never adds a publish label.
    assert not any("merge" in p for _, p, _ in writes)
    assert not any("cms/ready" in str(b) for _, _, b in writes)


def test_find_existing_draft_reads_the_marker():
    pulls = [
        {
            "body": "Automatically generated by Decap CMS\n\n<!-- email-draft:zzz -->",
            "head": {"ref": "cms/posts/2026-01-01-other"},
        },
        {
            "body": "Automatically generated by Decap CMS\n\n<!-- email-draft:abc -->",
            "head": {"ref": "cms/posts/2026-11-06-x"},
        },
        {"body": None, "head": {"ref": "feature"}},
    ]
    gh = client(FakeGitHubApi(pulls=pulls))
    assert gh.find_existing_draft("abc") == "2026-11-06-x"
    assert gh.find_existing_draft("nope") is None
    assert gh.find_existing_draft("ab") is None


def test_list_pulls_asks_for_all_states_newest_first():
    api = FakeGitHubApi()
    client(api).find_existing_draft("abc")
    assert api.calls[0][1] == "/pulls?state=all&sort=created&direction=desc&per_page=100"


def test_branch_and_file_existence():
    api = FakeGitHubApi()
    api.branches["cms/posts/2026-11-06-x"] = "s"
    api.files.add("_posts/2026-11-06-y.md")
    gh = client(api)
    assert gh.branch_exists("cms/posts/2026-11-06-x")
    assert not gh.branch_exists("cms/posts/2026-11-06-y")
    assert gh.file_exists("_posts/2026-11-06-y.md", "main")
    assert not gh.file_exists("_posts/2026-11-06-x.md", "main")


def test_http_error_carries_status_but_not_the_body():
    api = FakeGitHubApi()
    api.fail["POST /pulls"] = 422
    gh = client(api)
    with pytest.raises(github_draft.GitHubError) as info:
        gh.create_draft(
            entry_name="e",
            files={"a": b"b"},
            message_hash="h",
            base="main",
            head_sha="s",
            tree_sha="t",
        )
    assert info.value.status == 422
    assert SECRET_BODY not in str(info.value)

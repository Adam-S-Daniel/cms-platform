def test_verification_failure_replies_with_every_reason(site, dns, now, keys, monkeypatch, capsys):
    raw = m.deliver(
        m.sign(m.build_raw(to=m.STRANGER, body_text=BODY), keys["example.com"][0]),
        top_results=m.fastmail_auth_results(spf="fail"),
    )
    fm, gh = FakeFastmail(raw), FakeGitHubApi()
    monkeypatch.setattr(jmap, "urllib_transport", fm)
    monkeypatch.setattr(github_draft, "urllib_transport", gh)
    assert run(site, dns, now) == 1
    log = assert_clean(capsys)
    assert "checks=posting-address,fastmail-results" in log
    text, sent = reply_text(fm)
    assert sent["to"] == [{"name": None, "email": m.OWNER}]
    assert "(verification)" in text
    assert "not in the To or Cc line" in text and "SPF" in text
    assert "https://github.com/example-owner/example-site/actions/runs/987654" in text
    assert "DKIM-Signature" not in text and "messagingengine" not in text
    assert child_of_posting(fm) == "Failed"
    assert gh.writes() == []


def test_spoofed_sender_reply_goes_to_the_real_owner(site, dns, now, keys, monkeypatch, capsys):
    raw = m.deliver(
        m.build_raw(
            from_header="attacker@example.net",
            body_text=BODY,
            extra_headers=[("Reply-To", "attacker@example.net")],
        )
    )
    fm = FakeFastmail(raw)
    monkeypatch.setattr(jmap, "urllib_transport", fm)
    monkeypatch.setattr(github_draft, "urllib_transport", FakeGitHubApi())
    assert run(site, dns, now) == 1
    assert_clean(capsys)
    assert reply_text(fm)[1]["to"] == [{"name": None, "email": m.OWNER}]



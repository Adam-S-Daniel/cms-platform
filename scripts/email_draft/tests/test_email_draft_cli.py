"""End-to-end tests of `email_draft.py process` / `notify-failure` with every network faked.

The real verify/draft/jmap/github_draft code runs; only the HTTP transports and DNS are fakes.
"""

import email_draft
import github_draft
import jmap
import mailfactory as m
import pytest
from fakes import SECRET_BODY, FakeFastmail, FakeGitHubApi

FM_TOKEN = "fm-token-SECRET-1234"
GH_TOKEN = "gh-token-SECRET-5678"
ENV = {
    "FASTMAIL_API_TOKEN": FM_TOKEN,
    "EMAIL_DRAFT_ADDRESS": m.POSTING,
    "EMAIL_DRAFT_SENDER": m.OWNER,
    "GH_TOKEN": GH_TOKEN,
    "GITHUB_REPOSITORY": "example-owner/example-site",
    "GITHUB_SERVER_URL": "https://github.com",
    "GITHUB_RUN_ID": "987654",
}
BODY = "First paragraph of the secret post.\r\n\r\nSecond paragraph.\r\n"
# Strings that must never reach stdout/stderr.
NEVER_LOGGED = [
    m.OWNER,
    m.POSTING,
    "owner@",
    "post-7f3a9c",
    "A post from email",
    "secret post",
    FM_TOKEN,
    GH_TOKEN,
    "messagingengine",
    "DKIM-Signature",
    m.MESSAGE_ID.strip("<>"),
    SECRET_BODY,
    "example",
    "@",
]


def write_config(root, enabled=True):
    flag = "true" if enabled else "false"
    (root / "_config.yml").write_text(
        f'url: "https://example.com/"\ntimezone: America/New_York\n'
        f"cms:\n  email_drafts:\n    enabled: {flag}\n",
        encoding="utf-8",
    )


@pytest.fixture
def site(tmp_path):
    write_config(tmp_path)
    return tmp_path


@pytest.fixture
def raw(keys):
    return m.deliver(m.sign(m.build_raw(body_text=BODY), keys["example.com"][0]))


@pytest.fixture
def world(raw, monkeypatch):
    fm = FakeFastmail(raw, message_id=m.MESSAGE_ID.strip("<>"))
    gh = FakeGitHubApi()
    monkeypatch.setattr(jmap, "urllib_transport", fm)
    monkeypatch.setattr(github_draft, "urllib_transport", gh)
    return fm, gh


def run(site, dns, now, *extra, env=ENV):
    argv = ["process", "--email-id", "E1", "--site-root", str(site), *extra]
    return email_draft.main(argv, env=env, now=now, dnsfunc=dns)


def assert_clean(capsys):
    out, err = capsys.readouterr()
    for needle in NEVER_LOGGED:
        assert needle not in out and needle not in err, f"log leaked {needle!r}"
    return out + err


def reply_text(fm):
    [sent] = fm.sent
    return sent["email"]["bodyValues"]["b"]["value"], sent["email"]


def child_of_posting(fm):
    [box_id] = fm.emails["E1"]["mailboxIds"]
    return next(b["name"] for b in fm.mailboxes if b["id"] == box_id and b["parentId"] == "posting")


def test_success_creates_draft_replies_and_files_processed(site, dns, now, world, capsys):
    fm, gh = world
    assert run(site, dns, now) == 0
    log = assert_clean(capsys)
    assert "step=github result=ok pull=42" in log

    pr = next(b for mth, p, b in gh.calls if mth == "POST" and p == "/pulls")
    assert pr["head"] == "cms/posts/2026-11-06-a-post-from-email"
    assert pr["body"].startswith("Automatically generated by Decap CMS\n\n<!-- email-draft:")
    text, sent = reply_text(fm)
    assert sent["to"] == [{"name": None, "email": m.OWNER}]
    assert sent["subject"] == "Re: A post from email"
    assert "Title: A post from email" in text
    assert (
        "https://example.com/admin/#/collections/posts/entries/2026-11-06-a-post-from-email" in text
    )
    assert "select Publish" in text and "select Delete" in text
    assert child_of_posting(fm) == "Processed"
    assert fm.emails["E1"]["keywords"] == {"$seen": True}


def test_same_email_twice_is_deduplicated(site, dns, now, world, capsys):
    fm, gh = world
    assert run(site, dns, now) == 0
    marker_body = next(b for mth, p, b in gh.calls if p == "/pulls" and mth == "POST")["body"]
    gh.pulls = [{"body": marker_body, "head": {"ref": "cms/posts/2026-11-06-a-post-from-email"}}]
    gh.calls.clear()
    fm.sent.clear()
    fm.emails["E1"]["mailboxIds"] = {"posting": True}
    assert run(site, dns, now) == 0
    assert "step=dedupe result=already-drafted" in assert_clean(capsys)
    assert gh.writes() == []
    text, _ = reply_text(fm)
    assert "already" in text and "2026-11-06-a-post-from-email" in text
    assert child_of_posting(fm) == "Processed"


def test_existing_branch_or_file_gets_a_numbered_suffix(site, dns, now, world, capsys):
    fm, gh = world
    gh.branches["cms/posts/2026-11-06-a-post-from-email"] = "x"
    gh.files.add("_posts/2026-11-06-a-post-from-email-2.md")
    assert run(site, dns, now) == 0
    assert_clean(capsys)
    ref = next(b for mth, p, b in gh.calls if mth == "POST" and p == "/git/refs")["ref"]
    assert ref == "refs/heads/cms/posts/2026-11-06-a-post-from-email-3"


